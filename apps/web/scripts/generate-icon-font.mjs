#!/usr/bin/env node
/**
 * Regenerates the self-hosted Material Symbols subset used by <Icon> — issue #161.
 *
 *   node apps/web/scripts/generate-icon-font.mjs
 *   pnpm --filter @librarius/web generate:icon-font
 *
 * The full "Material Symbols Rounded" font Google Fonts served (the one still loaded
 * for every other typeface in index.html) was 407 kB gzipped — the complete icon set
 * (~4200 glyphs), downloaded to draw the ~38 names this app actually uses. It was also
 * fetched from fonts.gstatic.com, so it never arrived at all on a cold offline start,
 * glyphs missing exactly where the PWA needed them most.
 *
 * This script fetches that same font (the exact family/axes index.html used to
 * request), keeps only the ~38 glyphs `iconSubset.ts` lists, and writes the result as a
 * same-origin, service-worker-precached asset. Same approach `gen:api` uses for the
 * OpenAPI client: a generated artifact, committed, never hand-edited, regenerated by
 * hand when its source of truth changes.
 *
 * ## Why subsetting rather than inlined SVGs or a component per icon
 *
 * <Icon> stays a one-line `<span>` — every call site is unchanged, and picking a new
 * icon is still "find its Material Symbols name". The recurring cost is exactly one
 * step: add the name and its code point to `iconSubset.ts`, then rerun this script.
 * Forgetting either half fails loudly rather than shipping a blank glyph — see the guard
 * in `Icon.tsx`. Inlining SVGs (or one component per icon) would drop the font entirely,
 * but it turns "look up a name" into "source an SVG, normalise its viewBox, and wire two
 * variants for the states `fill` toggles between" for every one of the ~38 existing
 * icons up front, and for every one after — a much larger one-time cost, and a larger
 * recurring one, to save kilobytes this subset already saves.
 *
 * ## Why code points rather than the ligature names
 *
 * Material Symbols supports two ways to address a glyph: type its name as a ligature
 * (`arrow_back`, substituted by the font's GSUB table — what this app rendered before),
 * or use the Private Use Area code point Google publishes for it. Both resolve to the
 * exact same glyph — checked directly against this font before switching, by shaping
 * the ligature text and the code point separately and comparing the resulting glyph ID.
 *
 * Only the code point subsets cleanly. `subset-font` (hb-subset under the hood) selects
 * glyphs by *closure*: given a set of input letters, it keeps every ligature reachable
 * from them — not only the ones actually requested. Across ~38 names the requested
 * letters cover nearly the whole alphabet, so closure pulled in a large fraction of the
 * font's ~4200 icons: subsetting by ligature text only shrank it 18%. A code point maps
 * straight to one glyph with no closure involved, so the subset holds only the ~38
 * glyphs `iconSubset.ts` lists — `noLayoutClosure` is passed to make that explicit, and
 * it also drops the now-unused GSUB ligature table entirely.
 *
 * The font turned out to already be a **static** instance (no `fvar`/`gvar`): Google's
 * API collapses a family requested at a single point per axis, as index.html does
 * (`opsz,wght,FILL,GRAD@24,300,0,0`), down to one. `<Icon fill>`'s
 * `font-variation-settings: 'FILL' 1` was therefore already a no-op against the font
 * this app was loading — every call site that toggles `fill` also toggles `color`, which
 * is why that went unnoticed. The subset preserves that exact (in)behaviour; it is not
 * this script's place to fix it.
 */

import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import subsetFont from 'subset-font';
import { ICON_CODEPOINTS } from '../src/shared/ui/iconSubset.ts';

// The exact family + static axis point index.html requests today. Keep these two in
// sync: this script pulls the same font the app would otherwise download from Google
// every load, and a drifted query string would subset a font nobody actually uses.
const FONT_CSS_URL =
  'https://fonts.googleapis.com/css2?family=Material+Symbols+Rounded:opsz,wght,FILL,GRAD@24,300,0,0&display=swap';

// Where Google publishes the name -> code point table for this exact icon style, in
// case a future addition to iconSubset.ts needs a code point to put there.
const CODEPOINTS_REFERENCE_URL =
  'https://raw.githubusercontent.com/google/material-design-icons/master/variablefont/MaterialSymbolsRounded%5BFILL%2CGRAD%2Copsz%2Cwght%5D.codepoints';

// A real browser UA: Google Fonts serves a tiny "last-resort" @font-face without one.
const BROWSER_USER_AGENT =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';

const here = dirname(fileURLToPath(import.meta.url));
const outFile = join(here, '..', 'src', 'shared', 'styles', 'fonts', 'material-symbols-subset.woff2');

async function fetchText(url) {
  const res = await fetch(url, { headers: { 'User-Agent': BROWSER_USER_AGENT } });
  if (!res.ok) throw new Error(`GET ${url} → HTTP ${res.status}`);
  return res.text();
}

async function fetchBuffer(url) {
  const res = await fetch(url, { headers: { 'User-Agent': BROWSER_USER_AGENT } });
  if (!res.ok) throw new Error(`GET ${url} → HTTP ${res.status}`);
  return Buffer.from(await res.arrayBuffer());
}

console.log(`Fetching ${FONT_CSS_URL}`);
const css = await fetchText(FONT_CSS_URL);
const [, fontUrl] = css.match(/src:\s*url\((https:\/\/fonts\.gstatic\.com\/[^)]+)\)/) ?? [];
if (!fontUrl) {
  throw new Error(`Could not find a font URL in the Google Fonts CSS:\n${css}`);
}

console.log(`Downloading ${fontUrl}`);
const originalFont = await fetchBuffer(fontUrl);
console.log(`Original font: ${originalFont.byteLength.toLocaleString('en-US')} bytes`);

const names = Object.keys(ICON_CODEPOINTS);
const text = names.map((name) => String.fromCodePoint(ICON_CODEPOINTS[name])).join('');
console.log(
  `Subsetting to ${names.length} icons by code point (see ${CODEPOINTS_REFERENCE_URL} ` +
    `for the full name -> code point table): ${names.join(', ')}`
);

const subsetBuffer = await subsetFont(originalFont, text, {
  targetFormat: 'woff2',
  // Code points map straight to one glyph each — no ligature/ligature-closure involved
  // (see the file header). Without this flag hb-subset would still run its default GSUB
  // closure pass, which for this font is pure overhead once ligatures are unused.
  noLayoutClosure: true,
});
console.log(
  `Subset font: ${subsetBuffer.byteLength.toLocaleString('en-US')} bytes ` +
    `(${(100 - (subsetBuffer.byteLength / originalFont.byteLength) * 100).toFixed(1)}% smaller)`
);

await mkdir(dirname(outFile), { recursive: true });
await writeFile(outFile, subsetBuffer);
console.log(`Wrote ${outFile}`);
